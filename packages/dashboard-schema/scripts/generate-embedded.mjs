import { lstat, opendir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parse } from "yaml";
import { DASHBOARD_LIMITS, validateEmbeddedFiles } from "../src/index.js";

const here = dirname(fileURLToPath(import.meta.url));
const packageRoot = resolve(here, "..");
const dashboardDir = resolve(packageRoot, "dashboards");
const catalogDir = resolve(packageRoot, "../../apps/api/internal/querycatalog/defaults");
const outputFile = resolve(packageRoot, "../../apps/web/src/generated/dashboards.ts");
const compare = (left, right) => left < right ? -1 : left > right ? 1 : 0;

const queryRefs = new Set();
const bindings = [];
const catalogs = [];
for await (const entry of await opendir(catalogDir)) {
  if (!entry.isFile() || !entry.name.endsWith(".yaml")) continue;
  const catalog = parse(await readFile(resolve(catalogDir, entry.name), "utf8"));
  if (!catalog || catalog.version !== 1 || !Array.isArray(catalog.queries)) throw new Error(`invalid query catalog: ${entry.name}`);
  catalogs.push({ name: entry.name, catalog });
}
catalogs.sort((left, right) => compare(left.name, right.name));
for (const { name, catalog } of catalogs) {
  for (const query of catalog.queries) {
    if (!query || typeof query.ref !== "string") throw new Error(`invalid query entry: ${name}`);
    if (queryRefs.has(query.ref)) throw new Error(`duplicate queryRef: ${query.ref}`);
    queryRefs.add(query.ref);
  }
}
for (const { name, catalog } of catalogs) {
  for (const panel of catalog.panels ?? []) for (const series of panel.series ?? []) {
    if (typeof panel.id !== "string" || typeof series.key !== "string" || typeof series.query !== "string" || !queryRefs.has(series.query))
      throw new Error(`invalid panel binding: ${name}`);
    // panelTitle은 Builder 팔레트에서 사람이 읽을 그룹 이름입니다(카탈로그가 정본).
    bindings.push({ queryRef: series.query, panelId: panel.id, seriesKey: series.key, panelTitle: panel.title ?? panel.id });
  }
}
if (queryRefs.size === 0 || bindings.length === 0) throw new Error("query catalog contains no dashboard bindings");
const bindingRefs = new Set(bindings.map((binding) => binding.queryRef));
if (bindingRefs.size !== bindings.length) throw new Error("queryRef is bound to multiple dashboard series");
const bindingTargets = new Set(bindings.map((binding) => `${binding.panelId}\0${binding.seriesKey}`));
if (bindingTargets.size !== bindings.length) throw new Error("dashboard series is bound to multiple queryRefs");
bindings.sort((left, right) => compare(left.queryRef, right.queryRef) || compare(left.panelId, right.panelId) || compare(left.seriesKey, right.seriesKey));

const files = [];
for await (const entry of await opendir(dashboardDir)) {
  if (files.length >= DASHBOARD_LIMITS.files) throw new Error(`dashboard file count exceeds ${DASHBOARD_LIMITS.files}`);
  const name = entry.name;
  const path = resolve(dashboardDir, name);
  const stat = await lstat(path);
  const kind = stat.isSymbolicLink() ? "symlink" : stat.isFile() ? "file" : stat.isDirectory() ? "directory" : "other";
  if (stat.size > DASHBOARD_LIMITS.fileBytes) throw new Error(`dashboard file is too large: ${name}`);
  const text = kind === "file" ? await readFile(path, "utf8") : undefined;
  files.push({ name, kind, size: stat.size, text });
}
files.sort((left, right) => compare(left.name, right.name));
const dashboards = validateEmbeddedFiles(files, bindingRefs);
const source = `/* Generated by @k8s-dashboard/dashboard-schema. Do not edit. */\nimport type { DashboardDefinition } from "@k8s-dashboard/dashboard-schema";\nexport const embeddedDashboards = ${JSON.stringify(dashboards, null, 2)} as const satisfies readonly DashboardDefinition[];\nexport const embeddedDashboardBindings = ${JSON.stringify(bindings, null, 2)} as const;\n`;
await writeFile(outputFile, source, "utf8");
